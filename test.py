def require_env(name: str) -> str:
    value = os.getenv(name)
    if not value:
        sys.exit(f"Missing required environment variable: {name}")
    return value


def make_endpoints(tenant: str):
    """Build the IAM and API endpoints from the multi-tenant region moniker."""
    region = require_env("TEST_REGION")
    if region not in AuthRegionEndpoints or region not in ApiRegionEndpoints:
        sys.exit(f"Unknown TEST_REGION '{region}'. Valid: {', '.join(AuthRegionEndpoints.keys())}")
    return AuthRegionEndpoints[region](tenant), ApiRegionEndpoints[region]()


def make_client() -> CxOneClient:
    tenant = require_env("TEST_TENANT_ID")
    api_key = require_env("TEST_API_KEY")
    agent_name = os.getenv("CXONE_AGENT_NAME", "test")

    test_proxy_url = os.getenv("TEST_PROXY_URL")
    if test_proxy_url:
        # Intercepting test proxy: route traffic through it and ignore SSL verification errors.
        proxies = {"https": test_proxy_url}
        ssl_verify = False
        urllib3.disable_warnings(urllib3.exceptions.InsecureRequestWarning)
        print(f"WARNING: Using test proxy {test_proxy_url} with SSL verification disabled.")
    else:
        proxies = None
        ssl_verify = True

    auth_endpoint, api_endpoint = make_endpoints(tenant)
    print(f"Auth endpoint: {auth_endpoint}  API endpoint: {api_endpoint}")

    return CxOneClient.create_with_api_key(
        api_key,
        agent_name,
        auth_endpoint,
        api_endpoint,
        proxy=proxies,
        ssl_verify=ssl_verify,
        retries=15,
        retry_delay_s=5
    )


